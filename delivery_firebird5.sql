/* =====================================================================================
big pickle + opencode
atue como arquiteto em base de dados
gere um script de criacao das tabelas necessarias para um projeto de delivery de comida. 
tome como modelo o ifood. 
use firebird 5 
e guarde o resultado em um arquivo .sql em C:\Projects\Delivery

   PROJETO ..........: Delivery de Comida (modelo de marketplace inspirado no iFood)
   SGBD .............: Firebird 5.0 (dialect 3)
   ARQUIVO ..........: delivery_firebird5.sql
   OBJETIVO .........: Criacao completa do schema: dominios, tabelas, constraints,
                       indices, carga inicial dos dominios e triggers de integridade.

   COMO EXECUTAR
   1) Crie o banco (uma unica vez), com charset UTF8:

      CREATE DATABASE 'C:\Projects\Delivery\delivery.fdb'
        USER 'SYSDBA' PASSWORD 'masterkey'
        PAGE_SIZE 16384 DEFAULT CHARACTER SET UTF8;

   2) Execute este script com isql (ou IBExpert / FlameRobin / DBeaver em modo script):

      isql -u SYSDBA -p masterkey C:\Projects\Delivery\delivery.fdb -i delivery_firebird5.sql

      Se usar isql com banco UTF8, habilite antes a conexao:
        SET NAMES UTF8;

   NOTAS DE ARQUITETURA
   - Multi-tenant: MERCHANT (rede/marca) 1:N MERCHANT_UNIT (loja/ponto de venda).
     Pedido, cardapio e entrega sempre apontam para a UNIDADE, nunca para a rede.
   - Pedidos guardam SNAPSHOT de endereco, nome e preco do item. Alteracoes futuras
     no cardapio ou no cadastro do cliente nao reescrevem o historico financeiro.
   - Valores monetarios em NUMERIC(15,2). Nunca use FLOAT/DOUBLE para dinheiro.
   - Totais do pedido sao derivados (trigger) a partir dos itens + taxa - desconto.
   - line_total e coluna computada; nao deve ser informada em INSERT/UPDATE.
   - Dados de cartao: apenas bandeira e 4 ultimos digitos. Nunca armazene PAN/CVV.
   - Exclusao fisica de lojista com pedidos e bloqueada por FK: use is_active = FALSE.
   - Firebird nao cria indice automatico para FK: todos os indices necessarios estao
     declarados na secao 13.
   - Identity nao e atualizada quando se informa o ID manualmente. Ao carregar massa
     de dados de exemplo com IDs fixos, rode ao final, para cada tabela afetada:
       ALTER TABLE <tabela> ALTER COLUMN id RESTART WITH <maior_id + 1>;
     (a carga dos lookups na secao 14 ja faz esse ajuste)
   ===================================================================================== */


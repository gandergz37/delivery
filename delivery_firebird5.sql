/* ---- 15.1 Codigo amigavel do pedido ---------------------------------------------- */
CREATE TRIGGER trg_customer_order_bi FOR customer_order
ACTIVE BEFORE INSERT POSITION 0
AS
DECLARE VARIABLE v_seq BIGINT;
BEGIN
    IF (NEW.order_number IS NULL OR TRIM(NEW.order_number) = '') THEN
    BEGIN
        v_seq = NEXT VALUE FOR seq_order_number;
        NEW.order_number = 'PD' || LPAD(CAST(:v_seq AS VARCHAR(10)), 10, '0');
    END
END^

/* ---- 15.2 Totais do pedido (itens + frete - desconto) ---------------------------- */
CREATE TRIGGER trg_customer_order_biu FOR customer_order
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
DECLARE VARIABLE v_order_id BIGINT;
DECLARE VARIABLE v_items    NUMERIC(15,2);
BEGIN
    v_order_id = NEW.id;

    SELECT COALESCE(SUM(i.line_total), 0)
      FROM order_item i
     WHERE i.order_id = :v_order_id
      INTO :v_items;

    NEW.items_subtotal = :v_items;
    NEW.total_amount   = :v_items + NEW.delivery_fee - NEW.discount_total;
    NEW.updated_at     = CURRENT_TIMESTAMP;
END^

/* ---- 15.3 Historico automatico de status ----------------------------------------- */
CREATE TRIGGER trg_customer_order_ah FOR customer_order
ACTIVE AFTER INSERT OR UPDATE POSITION 0
AS
BEGIN
    IF (INSERTING) THEN
        INSERT INTO order_status_history (order_id, status_id, changed_by_type, notes)
        VALUES (NEW.id, NEW.status_id, 'SYSTEM', 'Pedido criado');
    ELSE IF (NEW.status_id <> OLD.status_id) THEN
        INSERT INTO order_status_history (order_id, status_id, changed_by_type, notes)
        VALUES (NEW.id, NEW.status_id, 'SYSTEM', NEW.status_note);
END^

/* ---- 15.4 Recalculo dos totais quando um item muda ------------------------------- */
CREATE TRIGGER trg_order_item_aiud FOR order_item
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 0
AS
DECLARE VARIABLE v_order_id     BIGINT;
DECLARE VARIABLE v_old_order_id BIGINT;
BEGIN
    IF (DELETING) THEN
        v_order_id = OLD.order_id;
    ELSE
        v_order_id = NEW.order_id;

    IF (UPDATING) THEN
        v_old_order_id = OLD.order_id;

    IF (EXISTS (SELECT 1 FROM customer_order o WHERE o.id = :v_order_id)) THEN
        UPDATE customer_order
           SET items_subtotal = COALESCE((SELECT SUM(i.line_total) FROM order_item i
                                           WHERE i.order_id = :v_order_id), 0),
               total_amount   = COALESCE((SELECT SUM(i.line_total) FROM order_item i
                                           WHERE i.order_id = :v_order_id), 0)
                                + delivery_fee - discount_total
         WHERE id = :v_order_id;

    IF (UPDATING AND v_old_order_id <> v_order_id
        AND EXISTS (SELECT 1 FROM customer_order o WHERE o.id = :v_old_order_id)) THEN
        UPDATE customer_order
           SET items_subtotal = COALESCE((SELECT SUM(i.line_total) FROM order_item i
                                           WHERE i.order_id = :v_old_order_id), 0),
               total_amount   = COALESCE((SELECT SUM(i.line_total) FROM order_item i
                                           WHERE i.order_id = :v_old_order_id), 0)
                                + delivery_fee - discount_total
         WHERE id = :v_old_order_id;
END^

/* ---- 15.5 Recalculo dos adicionais quando uma opcao muda ------------------------- */
CREATE TRIGGER trg_order_item_option_aiud FOR order_item_option
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 0
AS
DECLARE VARIABLE v_item_id     BIGINT;
DECLARE VARIABLE v_old_item_id BIGINT;
BEGIN
    IF (DELETING) THEN
        v_item_id = OLD.order_item_id;
    ELSE
        v_item_id = NEW.order_item_id;

    IF (UPDATING) THEN
        v_old_item_id = OLD.order_item_id;

    IF (EXISTS (SELECT 1 FROM order_item i WHERE i.id = :v_item_id)) THEN
        UPDATE order_item
           SET options_unit_total = COALESCE((SELECT SUM(o.unit_price_delta * o.quantity)
                                                FROM order_item_option o
                                               WHERE o.order_item_id = :v_item_id), 0)
         WHERE id = :v_item_id;

    IF (UPDATING AND v_old_item_id <> v_item_id
        AND EXISTS (SELECT 1 FROM order_item i WHERE i.id = :v_old_item_id)) THEN
        UPDATE order_item
           SET options_unit_total = COALESCE((SELECT SUM(o.unit_price_delta * o.quantity)
                                                FROM order_item_option o
                                               WHERE o.order_item_id = :v_old_item_id), 0)
         WHERE id = :v_old_item_id;
END^


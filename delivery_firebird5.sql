    quantity            SMALLINT DEFAULT 1 NOT NULL,
    notes               VARCHAR(500),
    line_total          COMPUTED BY (CAST((unit_price + options_unit_total) * quantity AS NUMERIC(15,2))),
    CONSTRAINT pk_order_item PRIMARY KEY (id),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_item_unit_price CHECK (unit_price >= 0),
    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id) REFERENCES customer_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_item_menu_item
        FOREIGN KEY (menu_item_id) REFERENCES menu_item (id) ON DELETE SET NULL
);


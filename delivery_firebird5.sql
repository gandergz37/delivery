CREATE DOMAIN dm_money AS NUMERIC(15,2);

CREATE DOMAIN dm_money_nn AS NUMERIC(15,2) DEFAULT 0 NOT NULL;

CREATE DOMAIN dm_percent AS NUMERIC(5,2) CHECK (VALUE BETWEEN 0 AND 100);

CREATE DOMAIN dm_rating AS NUMERIC(3,2) CHECK (VALUE BETWEEN 0 AND 5);

CREATE DOMAIN dm_latitude AS NUMERIC(10,7) CHECK (VALUE BETWEEN -90 AND 90);

CREATE DOMAIN dm_longitude AS NUMERIC(10,7) CHECK (VALUE BETWEEN -180 AND 180);

CREATE DOMAIN dm_name AS VARCHAR(150);

CREATE DOMAIN dm_email AS VARCHAR(254);

CREATE DOMAIN dm_phone AS VARCHAR(20);

CREATE DOMAIN dm_url AS VARCHAR(500);

CREATE DOMAIN dm_zipcode AS VARCHAR(10);

CREATE DOMAIN dm_uf AS CHAR(2);

CREATE DOMAIN dm_notes AS VARCHAR(1000);


